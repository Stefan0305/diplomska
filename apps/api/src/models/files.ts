import type { ModelInfo } from '@app/shared';
import { modelCategories, type ModelCategory } from '@app/shared';
import path from 'node:path';
import type { Model } from '../generated/prisma/client';

/** Uploaded GLBs live in this subfolder of the uploads folder. */
export const UPLOADED_MODELS_DIR = 'models';

/** Built-ins are served from /files/models (assets), uploads from /files/uploads. */
export function modelUrl(model: Pick<Model, 'ownerId' | 'filePath'>): string {
  const root = model.ownerId === null ? '/files/models' : '/files/uploads';
  return `${root}/${model.filePath}`;
}

function toCategory(value: string): ModelCategory {
  return (modelCategories as readonly string[]).includes(value)
    ? (value as ModelCategory)
    : 'other';
}

export function toModelInfo(model: Model): ModelInfo {
  return {
    id: model.id,
    name: model.name,
    category: toCategory(model.category),
    url: modelUrl(model),
    builtIn: model.ownerId === null,
    fileSize: model.fileSize,
    createdAt: model.createdAt.toISOString(),
  };
}

/** Built-ins first, then alphabetical: a stable, predictable library order. */
export function compareModels(a: ModelInfo, b: ModelInfo): number {
  if (a.builtIn !== b.builtIn) return a.builtIn ? -1 : 1;
  return a.name.localeCompare(b.name);
}

/**
 * Absolute path of an uploaded file. Refuses anything that would resolve outside the uploads
 * folder (defence in depth: file paths are generated by the server, never taken from users).
 */
export function resolveUploadPath(uploadDir: string, filePath: string): string {
  const root = path.resolve(uploadDir);
  const resolved = path.resolve(root, filePath);
  if (resolved !== root && resolved.startsWith(root + path.sep)) return resolved;
  throw new Error(`Refusing file path outside the uploads folder: ${filePath}`);
}
